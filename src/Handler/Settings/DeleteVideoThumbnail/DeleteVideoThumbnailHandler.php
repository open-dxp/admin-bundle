namespace OpenDxp\Bundle\AdminBundle\Handler\Settings\DeleteVideoThumbnail;

use OpenDxp\Model\Asset;
use OpenDxp\Model\Exception\ConfigWriteException;

final class DeleteVideoThumbnailHandler
{
    public function __invoke(DeleteVideoThumbnailPayload $payload): void
    {
        $pipe = Asset\Video\Thumbnail\Config::getByName($payload->name);

        if (!$pipe->isWriteable()) {
            throw new ConfigWriteException();
        }

        $pipe->delete();
    }
}
