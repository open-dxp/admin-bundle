namespace OpenDxp\Bundle\AdminBundle\Handler\DataObject\ClassDef\GetDocumentTypes;

use OpenDxp\Model\Document;

final class GetDocumentTypesHandler
{
    public function __invoke(): GetDocumentTypesResult
    {
        $typeItems = [];
        foreach (Document::getTypes() as $documentType) {
            $typeItems[] = ['text' => $documentType];
        }

        return new GetDocumentTypesResult(types: $typeItems);
    }
}
