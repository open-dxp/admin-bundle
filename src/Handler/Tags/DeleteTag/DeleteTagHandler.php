namespace OpenDxp\Bundle\AdminBundle\Handler\Tags\DeleteTag;

use OpenDxp\Model\Element\Tag;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;

final class DeleteTagHandler
{
    public function __invoke(DeleteTagPayload $payload): void
    {
        $tag = Tag::getById($payload->id);
        if (!$tag) {
            throw new NotFoundHttpException('Tag with ID ' . $payload->id . ' not found.');
        }

        $tag->delete();
    }
}
